import { mkdtemp, readFile, rm } from 'node:fs/promises'
import os from 'node:os'
import path from 'node:path'

import { validateBundleProvenance } from './bundle-provenance.mjs'
import { buildDeterministicCandidates } from './candidate-builds.mjs'
import { canonicalJSONString } from './canonical-json.mjs'
import { validateCommittedConsumerFixture } from './consumer-fixture.mjs'
import { reinspectPackedPackage } from './package-inspection.mjs'
import {
  readCanonicalJSON,
  readJSON,
  repositoryRoot,
  sha256Bytes,
} from './release-utils.mjs'
import {
  validateRuntimeAssetLock,
  validateRuntimeAssetVerification,
} from './runtime-assets.mjs'
import { validateRuntimeSourceProvenance } from './runtime-source-provenance.mjs'
import { generateCycloneDx } from './sbom.mjs'
import { sourceArchiveBytes } from './source-state.mjs'
import { validateCycloneDx } from './validate-cyclonedx.mjs'

function assertCanonicalEqual(actual, expected, location) {
  if (canonicalJSONString(actual) !== canonicalJSONString(expected)) {
    throw new TypeError(`${location} does not match independently regenerated evidence`)
  }
}

function assertBytesEqual(actual, expected, location) {
  if (!actual.equals(expected)) {
    throw new TypeError(`${location} does not match independently regenerated bytes`)
  }
}

export async function revalidateReleaseCandidate({
  outputDirectory,
  configuration,
  source,
  sourceOptions = {},
}) {
  const temporaryDirectory = await mkdtemp(path.join(os.tmpdir(), 'web-ide-release-revalidate-'))
  try {
    const rebuilt = await buildDeterministicCandidates({
      outputDirectory: temporaryDirectory,
      sourceCommit: source.commit,
      configuration: { ...configuration, sourceDateEpoch: source.sourceDateEpoch },
    })
    const candidatePath = path.join(outputDirectory, configuration.releaseAssetFilename)
    const candidateBytes = await readFile(candidatePath)
    assertBytesEqual(candidateBytes, rebuilt.tarballBytes, 'Candidate package')

    const inspection = await readCanonicalJSON(
      path.join(outputDirectory, 'package-inspection.json'),
      'package-inspection.json',
    )
    const reinspection = reinspectPackedPackage(candidateBytes, configuration.releaseAssetFilename)
    assertCanonicalEqual(inspection, reinspection, 'Package inspection')
    assertCanonicalEqual(inspection, rebuilt.inspection, 'Package inspection')
    const consumerFixture = await validateCommittedConsumerFixture(
      reinspection.tarball.sha512Integrity,
    )

    const provenance = validateBundleProvenance(await readCanonicalJSON(
      path.join(outputDirectory, 'bundle-provenance.json'),
      'bundle-provenance.json',
    ))
    assertCanonicalEqual(provenance, rebuilt.provenance, 'Bundle provenance')

    const sourceArchive = await sourceArchiveBytes(configuration, repositoryRoot, sourceOptions)
    assertBytesEqual(
      await readFile(path.join(outputDirectory, configuration.sourceAssetFilename)),
      sourceArchive.bytes,
      'Source archive',
    )
    const determinism = await readCanonicalJSON(
      path.join(outputDirectory, 'deterministic-builds.json'),
      'deterministic-builds.json',
    )
    assertCanonicalEqual(determinism, {
      ...rebuilt.determinism,
      exactTagSourceArchivesByteIdentical: true,
      sourceArchive: {
        filename: configuration.sourceAssetFilename,
        size: sourceArchive.size,
        sha256: sourceArchive.sha256,
      },
      buildInputs: rebuilt.buildInputs,
    }, 'Deterministic build evidence')

    const runtimeLock = validateRuntimeAssetLock(
      await readJSON(path.join(repositoryRoot, 'release/runtime-assets.lock.json')),
    )
    const runtimeSources = validateRuntimeSourceProvenance(
      await readJSON(path.join(repositoryRoot, 'release/runtime-source-provenance.json')),
      runtimeLock,
    )
    assertCanonicalEqual(
      await readCanonicalJSON(
        path.join(outputDirectory, 'runtime-source-provenance.json'),
        'runtime-source-provenance.json',
      ),
      runtimeSources,
      'Runtime source provenance',
    )
    validateRuntimeAssetVerification(
      await readCanonicalJSON(
        path.join(outputDirectory, 'runtime-assets-verification.json'),
        'runtime-assets-verification.json',
      ),
      runtimeLock,
    )

    const packageManifest = await readJSON(path.join(repositoryRoot, 'package.json'))
    const packageLock = await readJSON(path.join(repositoryRoot, 'package-lock.json'))
    const expectedSbom = await generateCycloneDx({
      provenancePath: path.join(outputDirectory, 'bundle-provenance.json'),
      runtimeLock,
      packageManifest,
      packageLock,
      candidate: inspection.tarball,
    })
    await validateCycloneDx(expectedSbom)
    const sbom = await readCanonicalJSON(
      path.join(outputDirectory, 'web-ide-0.2.0.cdx.json'),
      'web-ide-0.2.0.cdx.json',
    )
    await validateCycloneDx(sbom)
    assertCanonicalEqual(sbom, expectedSbom, 'CycloneDX SBOM')

    const licenseReportBytes = await readFile(path.join(outputDirectory, 'third-party-licenses.json'))
    await readCanonicalJSON(
      path.join(outputDirectory, 'third-party-licenses.json'),
      'third-party-licenses.json',
    )
    assertBytesEqual(licenseReportBytes, rebuilt.licenseReportBytes, 'License inventory')
    const licenseTextBytes = await readFile(path.join(outputDirectory, 'THIRD_PARTY_LICENSES.txt'))
    assertBytesEqual(licenseTextBytes, rebuilt.licenseTextBytes, 'Third-party license text')
    assertBytesEqual(
      licenseTextBytes,
      await readFile(path.join(repositoryRoot, 'THIRD_PARTY_LICENSES.txt')),
      'Shipped third-party license text',
    )
    const packedLicense = inspection.files.find((file) => file.path === 'THIRD_PARTY_LICENSES.txt')
    if (!packedLicense || packedLicense.sha256 !== sha256Bytes(licenseTextBytes)) {
      throw new TypeError('Packed third-party license text does not match regenerated evidence')
    }

    return {
      inspection,
      provenance,
      runtimeLock,
      runtimeSources,
      determinism,
      consumerFixture,
    }
  } finally {
    await rm(temporaryDirectory, { recursive: true, force: true })
  }
}
