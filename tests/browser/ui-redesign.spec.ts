import { expect, test } from '@playwright/test'
import { expectCleanBrowser, observeBrowserDiagnostics } from './browser-test-helpers'

test('scopes styles, shares the host theme and supports keyboard Manage and file recovery', async ({ page }) => {
  const diagnostics = observeBrowserDiagnostics(page)
  await page.goto('/?layout=redesign')
  await expect(page.locator('.monaco-editor')).toBeVisible()
  const title = page.getByRole('heading', { name: 'Host dialog title' })
  await expect(title).toHaveCSS('font-size', '24px')
  await expect(title).toHaveCSS('font-weight', '700')
  const manage = page.getByRole('button', { name: 'Manage', exact: true })
  await manage.focus(); await page.keyboard.press('Enter')
  await expect(page.getByRole('menuitemradio', { name: 'Light (Modern)' })).toBeFocused()
  await page.keyboard.press('ArrowUp'); await page.keyboard.press('Enter')
  await expect(page.locator('.web-ide-root')).toHaveAttribute('data-theme', 'dark')
  await expect(manage).toBeFocused()
  await expect(title).toHaveCSS('font-size', '24px')
  const tree = page.getByRole('tree', { name: 'Workspace files' })
  await tree.getByRole('treeitem', { name: 'helpers.py', exact: true }).click()
  await tree.focus(); await page.keyboard.press('Shift+F10')
  await expect(page.getByRole('menuitem', { name: 'New File…' })).toBeFocused()
  await page.keyboard.press('End'); await page.keyboard.press('Enter')
  await expect(tree.getByRole('treeitem', { name: 'helpers.py', exact: true })).toHaveCount(0)
  await page.getByRole('button', { name: 'Undo', exact: true }).click()
  await expect(tree.getByRole('treeitem', { name: 'helpers.py', exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'New File…', exact: true }).click()
  await page.getByRole('textbox', { name: 'New file name' }).fill('main.py')
  await page.keyboard.press('Enter')
  await expect(page.getByRole('alert').filter({ hasText: 'already exists' })).toContainText('already exists')
  await expect(page.getByRole('textbox', { name: 'New file name' })).toBeVisible()
  expectCleanBrowser(diagnostics)
})

test('compact navigation preserves mounted editor and terminal while exposing full-width views', async ({ page }) => {
  const diagnostics = observeBrowserDiagnostics(page)
  await page.setViewportSize({ width: 390, height: 844 })
  await page.goto('/?layout=redesign')
  const views = page.getByRole('tablist', { name: 'Workbench views' })
  await expect(views).toBeVisible()
  await expect(page.locator('.monaco-editor')).toBeVisible()
  const firstEditor = await page.locator('.monaco-editor').elementHandle()
  await views.getByRole('tab', { name: 'Workspace', exact: true }).click()
  await expect(page.getByRole('tree', { name: 'Workspace files' })).toBeVisible()
  await views.getByRole('tab', { name: 'Output', exact: true }).click()
  await expect(page.getByRole('tablist', { name: 'Workbench panels' })).toBeVisible()
  await views.getByRole('tab', { name: 'Code', exact: true }).click()
  expect(await firstEditor!.evaluate((element) => element.isConnected)).toBe(true)
  await expect(page.getByRole('textbox', { name: 'Terminal input' })).toBeVisible()
  expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBeLessThanOrEqual(390)
  expectCleanBrowser(diagnostics)
})

test('standalone controlled source editor changes host value without starting a runtime', async ({ page }) => {
  const diagnostics = observeBrowserDiagnostics(page)
  await page.goto('/?layout=source-editor')
  const editor = page.getByRole('textbox', { name: 'Assignment starter code' })
  // Monaco's native EditContext is an intentionally zero-width focus target.
  await expect(page.locator('.monaco-editor')).toBeVisible()
  await editor.focus(); await expect(editor).toBeFocused(); await page.keyboard.press('ControlOrMeta+A'); await page.keyboard.type('print("Updated")')
  await expect(page.getByRole('status', { name: 'Saved starter' })).toHaveText('print("Updated")')
  await expect(page.getByRole('toolbar', { name: 'Workbench toolbar' })).toHaveCount(0)
  await expect(page.getByRole('heading', { name: 'Host form title' })).toHaveCSS('font-size', '24px')
  expectCleanBrowser(diagnostics)
})


test('explicit source navigation exposes compact Code with the target focused and panes retained', async ({ page }) => {
  const diagnostics = observeBrowserDiagnostics(page)
  await page.setViewportSize({ width: 850, height: 900 })
  await page.goto('/?source=probe')
  await expect(page.locator('.monaco-editor')).toBeVisible()
  const views = page.getByRole('tablist', { name: 'Workbench views' })
  const code = views.getByRole('tab', { name: 'Code', exact: true })
  const workspace = views.getByRole('tab', { name: 'Workspace', exact: true })
  const output = views.getByRole('tab', { name: 'Output', exact: true })
  await page.getByRole('button', { name: 'Execution and source', exact: true }).click()
  const probe = page.getByRole('region', { name: 'Execution and source probe' })
  await expect(workspace).toHaveAttribute('aria-selected', 'true')
  await expect(probe).toBeVisible()
  // Monaco replaces its internal view DOM on a model switch. Its React-owned
  // container and runtime terminal must remain mounted.
  const editor = await page.locator('.monaco-editor').locator('..').elementHandle()
  const terminal = await page.locator('.xterm').elementHandle()
  await probe.getByRole('button', { name: 'Present current helper line' }).click()
  await expect(code).toHaveAttribute('aria-selected', 'true')
  await expect(page.getByRole('tab', { name: 'helpers.py' })).toBeVisible()
  await expect(page.getByRole('tab', { name: 'helpers.py' })).toHaveAttribute('aria-selected', 'true')
  await expect(page.getByLabel('Status bar', { exact: true })).toContainText('Ln 2, Col 1')
  await expect.poll(() => page.locator('.monaco-editor').evaluate((node) => node.contains(document.activeElement))).toBe(true)

  // Repeated navigation to the same file is a new explicit request too.
  await workspace.click()
  await probe.getByRole('button', { name: 'Present current helper line' }).click()
  await expect(code).toHaveAttribute('aria-selected', 'true')
  await output.click()
  await page.evaluate(() => {
    const scope = window as typeof window & {
      __webIDESourcePresentationProbe?: { source: { reveal(location: { path: string; line: number; column: number }): void } }
    }
    scope.__webIDESourcePresentationProbe!.source.reveal({ path: '/workspace/main.py', line: 4, column: 3 })
  })
  await expect(code).toHaveAttribute('aria-selected', 'true')
  await expect(page.getByLabel('Status bar', { exact: true })).toContainText('Ln 4, Col 3')
  await expect.poll(() => page.locator('.monaco-editor').evaluate((node) => node.contains(document.activeElement))).toBe(true)
  expect(await editor!.evaluate((node) => node.isConnected)).toBe(true)
  expect(await terminal!.evaluate((node) => node.isConnected)).toBe(true)
  // An old reveal must not prevent subsequent deliberate pane selection.
  await output.click()
  await expect(output).toHaveAttribute('aria-selected', 'true')
  expectCleanBrowser(diagnostics)
})

test('Go to Line stays within a narrow editor in both themes and returns editor focus', async ({ page }) => {
  const diagnostics = observeBrowserDiagnostics(page)
  await page.setViewportSize({ width: 390, height: 844 })
  await page.goto('/?layout=redesign')
  await expect(page.locator('.monaco-editor')).toBeVisible()
  for (const theme of ['Light (Modern)', 'Dark (Modern)']) {
    await page.getByRole('button', { name: 'Manage', exact: true }).click()
    await page.getByRole('menuitemradio', { name: theme, exact: true }).click()
    await page.locator('.monaco-editor').click({ position: { x: 120, y: 50 } })
    await page.keyboard.press('Control+g')
    const widget = page.locator('.quick-input-widget:visible')
    await expect(widget).toBeVisible()
    const box = await widget.boundingBox()
    const editorBox = await page.locator('.monaco-editor').boundingBox()
    expect(box!.x).toBeGreaterThanOrEqual(editorBox!.x)
    expect(box!.x + box!.width).toBeLessThanOrEqual(editorBox!.x + editorBox!.width)
    expect(box!.x + box!.width).toBeLessThanOrEqual(390)
    const input = widget.locator('input')
    await expect(input).toBeFocused()
    await input.fill(':3')
    await page.keyboard.press('Enter')
    await expect(widget).toBeHidden()
    await expect(page.getByLabel('Status bar', { exact: true })).toContainText('Ln 3, Col 1')
    await expect.poll(() => page.locator('.monaco-editor').evaluate((node) => node.contains(document.activeElement))).toBe(true)
    expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBeLessThanOrEqual(390)
  }
  expectCleanBrowser(diagnostics)
})


test('compact Explorer activation exposes Code for new and active files without losing the caret', async ({ page }) => {
  const diagnostics = observeBrowserDiagnostics(page)
  await page.setViewportSize({ width: 850, height: 900 })
  await page.goto('/?layout=redesign')
  const views = page.getByRole('tablist', { name: 'Workbench views' })
  await expect(views).toBeVisible()
  const code = views.getByRole('tab', { name: 'Code', exact: true })
  const workspace = views.getByRole('tab', { name: 'Workspace', exact: true })
  const tree = page.getByRole('tree', { name: 'Workspace files' })
  await workspace.click()
  await tree.getByRole('treeitem', { name: 'helpers.py', exact: true }).click()
  await expect(code).toHaveAttribute('aria-selected', 'true')
  await expect.poll(() => page.locator('.monaco-editor').evaluate((node) => node.contains(document.activeElement))).toBe(true)
  await page.keyboard.press('Control+g')
  await page.locator('.quick-input-widget:visible input').fill(':2:5')
  await page.keyboard.press('Enter')
  const status = page.getByLabel('Status bar', { exact: true })
  await expect(status).toContainText('Ln 2, Col 5')
  // Monaco replaces its internal view DOM on a model switch. Its React-owned
  // container and runtime terminal must remain mounted.
  const editor = await page.locator('.monaco-editor').locator('..').elementHandle()
  const terminal = await page.locator('.xterm').elementHandle()
  // Reopening the selected file is still an explicit activation request.
  await workspace.click()
  await tree.getByRole('treeitem', { name: 'helpers.py', exact: true }).click()
  await expect(code).toHaveAttribute('aria-selected', 'true')
  await expect(status).toContainText('Ln 2, Col 5')
  await expect.poll(() => page.locator('.monaco-editor').evaluate((node) => node.contains(document.activeElement))).toBe(true)
  await workspace.click()
  await tree.getByRole('treeitem', { name: 'main.py', exact: true }).click()
  await expect(code).toHaveAttribute('aria-selected', 'true')
  await expect(page.getByRole('tab', { name: 'main.py' })).toHaveAttribute('aria-selected', 'true')
  await workspace.click()
  await tree.getByRole('treeitem', { name: 'helpers.py', exact: true }).click()
  await expect(code).toHaveAttribute('aria-selected', 'true')
  await expect(status).toContainText('Ln 2, Col 5')
  await workspace.click()
  await page.getByRole('button', { name: 'New File…', exact: true }).click()
  await page.getByRole('textbox', { name: 'New file name' }).fill('notes.py')
  await page.keyboard.press('Enter')
  await expect(code).toHaveAttribute('aria-selected', 'true')
  await expect(page.getByRole('tab', { name: 'notes.py' })).toHaveAttribute('aria-selected', 'true')
  await expect.poll(() => page.locator('.monaco-editor').evaluate((node) => node.contains(document.activeElement))).toBe(true)
  expect(await editor!.evaluate((node) => node.isConnected)).toBe(true)
  expect(await terminal!.evaluate((node) => node.isConnected)).toBe(true)
  expectCleanBrowser(diagnostics)
})
